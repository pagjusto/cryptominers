export const SITE_LANG_STORAGE_KEY = 'cryptozombies_site_lang_v1';

export function getStoredSiteLang() {
  if (typeof window === 'undefined') return 'pt';
  try {
    const saved = localStorage.getItem(SITE_LANG_STORAGE_KEY);
    return saved === 'en' ? 'en' : 'pt';
  } catch (e) {
    return 'pt';
  }
}
